export function isSupportedLocale(code) {
  return SUPPORTED_LOCALES.some((entry) => entry.code === code)
}

export function resolveLocale(code) {
  return isSupportedLocale(code) ? code : DEFAULT_LOCALE
}

export function htmlLangFor(code) {
  return SUPPORTED_LOCALES.find((entry) => entry.code === code)?.htmlLang || 'en-AU'
}

export function isRtlLocale(code) {
  return SUPPORTED_LOCALES.find((entry) => entry.code === code)?.dir === 'rtl'
}

export function t(code, key) {
  const locale = resolveLocale(code)
  return MESSAGES[locale]?.[key] || MESSAGES[DEFAULT_LOCALE]?.[key] || key
}
